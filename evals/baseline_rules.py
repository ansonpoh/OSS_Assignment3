#!/usr/bin/env python3
"""A stronger conventional-automation baseline: a keyword labeller with a
template-completeness reply, the kind of rules a GitHub labeler action or an
issue-ops bot can express without a model.

Rules (title and body only, no model):
  - title tag [BUG] -> bug; [REQUEST] or "feature request" -> enhancement
  - title starts with "how", "question" or ends with "?" -> question
  - "readme", "docs" or "documentation" in the title -> documentation
  - "vulnerab", "CVE-" or "security" in title or body -> upstream
  - bug with no fenced code block in the body -> "more information needed"
  - a canned comment for every label except a bug with code (repro request,
    "feature requests need approval", "use Discussions", "report upstream")
  - no rule matched -> no label, no comment

Scores each golden case on the same expectations as the agent: labels must
include / must not include, and the comment decision (required / none).
Comment content is not judged, which favours the baseline.

  python evals/baseline_rules.py    # writes evals/golden/baseline_rules.md
"""
import glob
import json
import os
import re

ROOT = os.path.join(os.path.dirname(__file__), "golden")


def triage(title, body):
    t, b = title.lower(), (body or "").lower()
    labels = []
    if t.startswith("[bug]"):
        labels.append("bug")
    if t.startswith("[request]") or "feature request" in t:
        labels.append("enhancement")
    if t.startswith(("how", "question")) or t.rstrip().endswith("?"):
        labels.append("question")
    if re.search(r"\b(readme|docs|documentation)\b", t):
        labels.append("documentation")
    if re.search(r"vulnerab|cve-|security", t + " " + b):
        labels.append("upstream")
    if "bug" in labels and "```" not in b:
        labels.append("more information needed")
    comment = bool(labels) and labels != ["bug"]
    return labels[:3], comment


def judge(exp, labels, comment):
    fails = [f"missing label '{l}'" for l in exp["labels_include"] if l not in labels]
    fails += [f"forbidden label '{l}'" for l in exp["labels_exclude"] if l in labels]
    if exp.get("no_labels") and labels:
        fails.append("expected no labels (noop)")
    if exp["comment"] == "required" and not comment:
        fails.append("expected a comment, got none")
    if exp["comment"] == "none" and comment:
        fails.append("expected no comment")
    return fails


def main():
    rows, passed = [], 0
    for sub in ("cases", "adversarial", "heldout"):
        for d in sorted(glob.glob(os.path.join(ROOT, sub, "*"))):
            inp = json.load(open(os.path.join(d, "input.json"), encoding="utf-8"))
            exp = json.load(open(os.path.join(d, "expected.json"), encoding="utf-8"))
            labels, comment = triage(inp["title"], inp["body"])
            fails = judge(exp, labels, comment)
            passed += not fails
            rows.append(
                f"| {os.path.basename(d)} | {'PASS' if not fails else 'FAIL'} "
                f"| {', '.join(labels) or '-'} | {int(comment)} | {'; '.join(fails) or '-'} |"
            )
    out = [
        "# Keyword-rule baseline\n",
        f"{passed}/{len(rows)} cases pass (labels and comment decision only; "
        "comment content not judged). Generated by `evals/baseline_rules.py`.\n",
        "| Case | Verdict | Labels | Comment | Failures |",
        "| --- | --- | --- | --- | --- |",
        *rows,
    ]
    open(os.path.join(ROOT, "baseline_rules.md"), "w", encoding="utf-8").write("\n".join(out) + "\n")
    print(out[1])


if __name__ == "__main__":
    main()
