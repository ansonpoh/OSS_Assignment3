#!/usr/bin/env python3
"""Build a reviewer's packet for the submitted run: for every case, the issue
as filed, what maintainers actually did, the expected outcome, and the agent's
labels and comment side by side. Used to fill in evals/golden/review.md.

  python evals/review_packet.py        # writes evals/golden/review_packet.md
"""
import glob
import json
import os
import re

ROOT = os.path.join(os.path.dirname(__file__), "golden")
FOOTER = "<sub>Automated first-response triage"
BODY_CHARS = 700
COMMENT_CHARS = 500
ASSOC = {
    "NONE": "non-member",
    "CONTRIBUTOR": "past contributor",
    "OWNER": "repository owner (constructed case)",
}


def load(path):
    return json.load(open(path)) if os.path.exists(path) else None


def clean(text, limit):
    text = re.sub(r"<!--.*?-->", "", text or "", flags=re.S).strip()
    text = re.sub(r"\n{3,}", "\n\n", text)
    return text[:limit] + (" [...]" if len(text) > limit else "")


def quote(text):
    return "\n".join("> " + line for line in text.splitlines()) or "> (empty)"


def what_happened(ev):
    if ev is None:
        return ["Constructed adversarial case: no upstream history."]
    lines = [
        f"Final state: **{ev['final_state']}**"
        + (f" ({ev['state_reason']})" if ev.get("state_reason") else "")
        + f"; labels: {', '.join(ev['final_labels']) or 'none'}."
    ]
    for c in ev["comments"]:
        if c["author"].endswith("[bot]"):
            continue
        who = f"{c['author']} ({'maintainer' if c['is_maintainer'] else c['association'].lower()})"
        lines.append(
            f"- {who}, {c['at'][:10]}: " + clean(c["body"], 300).replace("\n", " ")
        )
    return lines


def case_section(d):
    cid = os.path.basename(d)
    inp, exp = load(os.path.join(d, "input.json")), load(
        os.path.join(d, "expected.json")
    )
    ev, act = load(os.path.join(d, "evidence.json")), load(
        os.path.join(d, "actual", "actual.json")
    )
    src = inp.get("source_url") or ""
    out = [f'<a id="{cid}"></a>', "", f"## {cid}: {inp['title']}", ""]
    out.append(
        f"Kind: `{exp['kind']}`. Filed {inp['created_at'][:10]} by a "
        f"{ASSOC.get(inp['author_association'], inp['author_association'].lower())}"
        + (f" ([upstream]({src}))" if src else "")
        + "."
    )
    out += [
        "",
        "**Issue as filed** (HTML comments removed, truncated):",
        "",
        quote(clean(inp["body"], BODY_CHARS)),
        "",
    ]
    out += ["**What really happened upstream:**", "", *what_happened(ev), ""]
    out.append(
        f"**Expected:** labels include {exp['labels_include'] or '-'}, exclude {exp['labels_exclude'] or '-'}; "
        f"comment {exp['comment']}. {exp['rationale']}"
    )
    out.append("")
    if act:
        out.append(
            f"**Agent** ([sandbox #{act['sandbox_issue']}]({act['run_url'].split('/actions/')[0]}/issues/{act['sandbox_issue']}), "
            f"run {act.get('run_id')}): labels {act['labels_added_by_agent'] or 'none'}; "
            f"automatic verdict **{act['verdict']}**"
            + (f" ({'; '.join(act['failures'])})" if act["failures"] else "")
            + "."
        )
        out.append("")
        for c in act["agent_comments"]:
            out += [quote(clean(c.split(FOOTER)[0], COMMENT_CHARS)), ""]
        if not act["agent_comments"]:
            out += ["(no comment)", ""]
    out += ["**Your verdict:** correct / acceptable / wrong. Reason:", "", "---", ""]
    return "\n".join(out)


def main():
    dirs = sorted(glob.glob(os.path.join(ROOT, "cases", "*"))) + sorted(
        glob.glob(os.path.join(ROOT, "adversarial", "*"))
    )
    head = [
        "# Review packet for the submitted run",
        "",
        "One section per case: the issue, what maintainers did, what was expected, and what the",
        "agent did. Read each and record a verdict in `review.md`. Generated by",
        "`evals/review_packet.py` from the case files; links open the full issue.",
        "",
        "Verdicts: **correct** = a maintainer could have posted it; **acceptable** = right",
        "direction with a flaw; **wrong** = would mislead the reporter or waste maintainer time.",
        "",
        "Cases: "
        + " · ".join(f"[{os.path.basename(d)}](#{os.path.basename(d)})" for d in dirs),
        "",
        "---",
        "",
    ]
    with open(os.path.join(ROOT, "review_packet.md"), "w") as f:
        f.write("\n".join(head) + "\n".join(case_section(d) for d in dirs))
    print("wrote", os.path.join(ROOT, "review_packet.md"))


if __name__ == "__main__":
    main()
